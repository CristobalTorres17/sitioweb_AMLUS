import Authenticated from '@/Layouts/AuthenticatedLayout';
import { Head, Link, useForm, usePage } from '@inertiajs/react';
import { useState, useCallback, useRef } from 'react';
import RichTextEditor from '@/Components/RichTextEditor';
import MediaPicker from '@/Components/MediaPicker';
import PrimaryButton from '@/Components/PrimaryButton';
import SecondaryButton from '@/Components/SecondaryButton';
import DangerButton from '@/Components/DangerButton';
import Modal from '@/Components/Modal';
import VersionHistory from './VersionHistory';

type PageData = {
    id: number;
    title: string;
    slug: string;
    content: string;
    description: string;
    meta_description: string;
    meta_keywords: string;
    og_image_media_id: number | null;
    is_published: boolean;
    published_at: string | null;
    versions_count: number;
    deleted_at: string | null;
};

type FormData = {
    title: string;
    slug: string;
    content: string;
    description: string;
    meta_description: string;
    meta_keywords: string;
    og_image_media_id: number | null;
};

export default function Edit() {
    const props: any = usePage().props;
    const page = props.page as PageData;
    const pageBlocks = (props.pageBlocks ?? []) as any[];
    const pageBlocksSlug = (props.pageBlocksSlug as string | undefined) || page.slug;
    const auth = props.auth;

    const form = useForm<FormData>({
        title: page.title,
        slug: page.slug,
        content: page.content,
        description: page.description,
        meta_description: page.meta_description,
        meta_keywords: page.meta_keywords,
        og_image_media_id: page.og_image_media_id,
    });

    const [showMediaPicker, setShowMediaPicker] = useState(false);
    const [showVersionHistory, setShowVersionHistory] = useState(false);
    const [showDeleteModal, setShowDeleteModal] = useState(false);
    const [slugAutoGenerated, setSlugAutoGenerated] = useState(false);

    // Auto-generate slug from title
    const generateSlug = useCallback((title: string) => {
        if (!title.trim()) {
            form.setData('slug', '');
            return;
        }

        const slug = title
            .toLowerCase()
            .trim()
            .replace(/[^\w\s-]/g, '')
            .replace(/\s+/g, '-')
            .replace(/-+/g, '-')
            .replace(/^-+|-+$/g, '');

        form.setData('slug', slug);
        setSlugAutoGenerated(true);
    }, []);

    const handleTitleChange = (e: React.ChangeEvent<HTMLInputElement>) => {
        const newTitle = e.target.value;
        form.setData('title', newTitle);

        if (!form.data.slug || slugAutoGenerated) {
            generateSlug(newTitle);
        }
    };

    const handleSlugChange = (e: React.ChangeEvent<HTMLInputElement>) => {
        form.setData('slug', e.target.value);
        setSlugAutoGenerated(false);
    };

    const handleMediaSelect = (media: any) => {
        form.setData('og_image_media_id', media.id);
        setShowMediaPicker(false);
    };

    const handleSubmit = (e: React.FormEvent) => {
        e.preventDefault();
        form.patch(route('pages.update', page.id), {
            onSuccess: () => {
                // Success - will redirect
            },
        });
    };

    const togglePublish = () => {
        const endpoint = page.is_published ? 'pages.unpublish' : 'pages.publish';
        form.post(route(endpoint, page.id), {
            onSuccess: () => {
                // Will refresh
            },
        });
    };

    const confirmDelete = () => {
        form.delete(route('pages.destroy', page.id), {
            onSuccess: () => {
                setShowDeleteModal(false);
            },
        });
    };

    return (
        <Authenticated>
            <Head title={`Editar: ${page.title}`} />

            <div className="mb-6 flex items-center justify-end">
                <div className="flex gap-2">
                    {page.versions_count > 0 && (
                        <button
                            type="button"
                            onClick={() => setShowVersionHistory(true)}
                            className="px-4 py-2 bordered border-border rounded-lg text-primary font-medium hover:bg-gray-50 transition"
                        >
                            📜 Historial ({page.versions_count})
                        </button>
                    )}
                </div>
            </div>

            <form onSubmit={handleSubmit} className="space-y-6">
                <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
                    {/* Main Content */}
                    <div className="lg:col-span-2 space-y-6">
                        {/* Card: Basic Info */}
                        <div className="rounded-lg bg-surface border border-border p-6 shadow-sm">
                            <h3 className="text-lg font-medium text-primary mb-4">
                                Información Básica
                            </h3>

                            {/* Title */}
                            <div className="mb-4">
                                <label className="block text-sm font-medium text-primary mb-2">
                                    Título *
                                </label>
                                <input
                                    type="text"
                                    value={form.data.title}
                                    onChange={handleTitleChange}
                                    placeholder="Título de la página"
                                    className="w-full px-4 py-2 border border-border rounded-lg bg-white text-primary focus:outline-none focus:ring-2 focus:ring-primary/20"
                                />
                                {form.errors.title && (
                                    <p className="text-red-600 text-xs mt-2">{form.errors.title}</p>
                                )}
                            </div>

                            {/* Slug */}
                            <div className="mb-4">
                                <label className="block text-sm font-medium text-primary mb-2">
                                    Slug *
                                </label>
                                <div className="flex gap-2">
                                    <div className="flex-1">
                                        <input
                                            type="text"
                                            value={form.data.slug}
                                            onChange={handleSlugChange}
                                            placeholder="url-amigable"
                                            className="w-full px-4 py-2 border border-border rounded-lg bg-white text-primary focus:outline-none focus:ring-2 focus:ring-primary/20"
                                        />
                                    </div>
                                    <button
                                        type="button"
                                        onClick={() => generateSlug(form.data.title)}
                                        className="px-4 py-2 border border-border rounded-lg bg-gray-50 text-primary font-medium hover:bg-gray-100 transition whitespace-nowrap"
                                    >
                                        Auto-generar
                                    </button>
                                </div>
                                {form.errors.slug && (
                                    <p className="text-red-600 text-xs mt-2">{form.errors.slug}</p>
                                )}
                            </div>

                            {/* Description */}
                            <div>
                                <label className="block text-sm font-medium text-primary mb-2">
                                    Descripción Breve
                                </label>
                                <textarea
                                    value={form.data.description}
                                    onChange={e => form.setData('description', e.target.value)}
                                    placeholder="Breve descripción de la página..."
                                    rows={3}
                                    className="w-full px-4 py-2 border border-border rounded-lg bg-white text-primary focus:outline-none focus:ring-2 focus:ring-primary/20"
                                />
                            </div>
                        </div>

                        {/* Card: Content */}
                        <div className="rounded-lg bg-surface border border-border p-6 shadow-sm">
                            <h3 className="text-lg font-medium text-primary mb-4">Contenido *</h3>
                            <RichTextEditor
                                value={form.data.content}
                                onChange={content => form.setData('content', content)}
                                placeholder="Escribe el contenido de la página..."
                            />
                            {form.errors.content && (
                                <p className="text-red-600 text-xs mt-2">{form.errors.content}</p>
                            )}
                        </div>

                        <div className="rounded-lg bg-surface border border-border p-6 shadow-sm">
                            <div className="flex items-start justify-between gap-4">
                                <div>
                                    <h3 className="text-lg font-medium text-primary">
                                        Bloques de contenido ({pageBlocks.length})
                                    </h3>
                                    <p className="mt-1 text-sm text-text-secondary">
                                        Asigna bloques CMS a esta página. El botón abre el editor
                                        con el slug de la página ya vinculado.
                                    </p>
                                </div>

                                <Link
                                    href={
                                        route('cms-blocks.create') +
                                        `?page=${encodeURIComponent(pageBlocksSlug)}&zone=after_hero`
                                    }
                                    className="shrink-0 rounded-md bg-primary px-4 py-2 text-sm font-semibold text-gold transition hover:opacity-90"
                                >
                                    + Agregar bloque
                                </Link>
                            </div>

                            {pageBlocks.length === 0 ? (
                                <div className="mt-4 rounded-lg border border-dashed border-border bg-white p-5 text-sm text-text-secondary">
                                    Esta página no tiene bloques CMS todavía. Usa el botón para
                                    crear el primero y dejarlo vinculado a esta vista.
                                </div>
                            ) : (
                                <div className="mt-4 space-y-2">
                                    {pageBlocks.map((block: any) => (
                                        <div
                                            key={block.id}
                                            className="flex items-center justify-between gap-4 rounded-lg border border-border bg-white px-4 py-3"
                                        >
                                            <div className="min-w-0">
                                                <div className="truncate text-sm font-medium text-primary">
                                                    {block.name}
                                                </div>
                                                <div className="mt-0.5 flex items-center gap-2 text-xs text-text-secondary">
                                                    <span className="rounded bg-gray-100 px-1.5 py-0.5 font-mono">
                                                        {block.template_key}
                                                    </span>
                                                    <span>zona: {block.zone}</span>
                                                    <span
                                                        className={`rounded px-1.5 py-0.5 font-semibold ${
                                                            block.is_active
                                                                ? 'bg-green-100 text-green-700'
                                                                : 'bg-gray-100 text-gray-500'
                                                        }`}
                                                    >
                                                        {block.is_active ? 'activo' : 'inactivo'}
                                                    </span>
                                                </div>
                                            </div>

                                            <Link
                                                href={route('cms-blocks.edit', block.id)}
                                                className="shrink-0 rounded border border-border px-3 py-1.5 text-xs font-medium text-primary hover:bg-gray-50"
                                            >
                                                Editar
                                            </Link>
                                        </div>
                                    ))}
                                </div>
                            )}

                            <div className="mt-4 rounded-lg border border-border bg-gray-50 p-4 text-sm text-text-secondary">
                                <div className="font-medium text-primary">Cómo funciona</div>
                                Los bloques se agrupan por zona.{' '}
                                <span className="font-mono font-semibold">after_hero</span>
                                se usa para el primer bloque principal de esta página;{' '}
                                <span className="font-mono font-semibold">mid_content</span>y{' '}
                                <span className="font-mono font-semibold">before_footer</span>{' '}
                                cubren el resto.
                            </div>
                        </div>
                    </div>

                    {/* Sidebar */}
                    <div className="lg:col-span-1 space-y-6">
                        {/* Card: SEO */}
                        <div className="rounded-lg bg-surface border border-border p-6 shadow-sm">
                            <h3 className="text-lg font-medium text-primary mb-4">SEO</h3>

                            {/* Meta Description */}
                            <div className="mb-4">
                                <label className="block text-sm font-medium text-primary mb-2">
                                    Meta Description
                                </label>
                                <textarea
                                    value={form.data.meta_description}
                                    onChange={e => form.setData('meta_description', e.target.value)}
                                    placeholder="Descripción para motores de búsqueda..."
                                    maxLength={160}
                                    rows={2}
                                    className="w-full px-3 py-2 text-sm border border-border rounded-lg bg-white text-primary focus:outline-none focus:ring-2 focus:ring-primary/20"
                                />
                                <p className="text-xs text-text-secondary mt-1">
                                    {form.data.meta_description.length}/160 caracteres
                                </p>
                                {form.errors.meta_description && (
                                    <p className="text-red-600 text-xs mt-2">
                                        {form.errors.meta_description}
                                    </p>
                                )}
                            </div>

                            {/* Meta Keywords */}
                            <div>
                                <label className="block text-sm font-medium text-primary mb-2">
                                    Meta Keywords
                                </label>
                                <input
                                    type="text"
                                    value={form.data.meta_keywords}
                                    onChange={e => form.setData('meta_keywords', e.target.value)}
                                    placeholder="palabra1, palabra2, palabra3"
                                    className="w-full px-3 py-2 text-sm border border-border rounded-lg bg-white text-primary focus:outline-none focus:ring-2 focus:ring-primary/20"
                                />
                                <p className="text-xs text-text-secondary mt-1">
                                    Separadas por comas
                                </p>
                            </div>
                        </div>

                        {/* Card: OG Image */}
                        <div className="rounded-lg bg-surface border border-border p-6 shadow-sm">
                            <h3 className="text-lg font-medium text-primary mb-4">Imagen OG</h3>

                            {form.data.og_image_media_id ? (
                                <div>
                                    <p className="text-sm text-text-secondary mb-3">
                                        Imagen seleccionada (ID: {form.data.og_image_media_id})
                                    </p>
                                    <button
                                        type="button"
                                        onClick={() => setShowMediaPicker(true)}
                                        className="w-full px-3 py-2 text-sm border border-border rounded-lg bg-gray-50 text-primary font-medium hover:bg-gray-100 transition"
                                    >
                                        Cambiar Imagen
                                    </button>
                                    <button
                                        type="button"
                                        onClick={() => form.setData('og_image_media_id', null)}
                                        className="w-full px-3 py-2 text-sm text-red-600 mt-2"
                                    >
                                        Eliminar
                                    </button>
                                </div>
                            ) : (
                                <button
                                    type="button"
                                    onClick={() => setShowMediaPicker(true)}
                                    className="w-full px-3 py-2 text-sm border border-border rounded-lg bg-gray-50 text-primary font-medium hover:bg-gray-100 transition"
                                >
                                    Seleccionar Imagen
                                </button>
                            )}
                            <p className="text-xs text-text-secondary mt-2">
                                Imagen para compartir en redes sociales
                            </p>
                        </div>

                        {/* Card: Status */}
                        <div className="rounded-lg bg-surface border border-border p-6 shadow-sm">
                            <h3 className="text-lg font-medium text-primary mb-4">Estado</h3>
                            <button
                                type="button"
                                onClick={togglePublish}
                                className={`w-full px-4 py-2 rounded-lg font-medium transition text-white ${
                                    page.is_published
                                        ? 'bg-green-600 hover:bg-green-700'
                                        : 'bg-gray-400 hover:bg-gray-500'
                                }`}
                            >
                                {page.is_published ? '✓ Publicada' : '○ Borrador'}
                            </button>
                            <p className="text-xs text-text-secondary mt-3">
                                {page.is_published
                                    ? `Publicada el ${new Date(
                                          page.published_at!,
                                      ).toLocaleDateString('es-ES')}`
                                    : 'La página no está publicada'}
                            </p>
                        </div>

                        {/* Card: Danger Zone */}
                        <div className="rounded-lg bg-red-50 border border-red-200 p-6">
                            <h3 className="text-lg font-medium text-red-700 mb-4">
                                Zona de Riesgo
                            </h3>
                            <DangerButton
                                onClick={() => setShowDeleteModal(true)}
                                className="w-full"
                            >
                                {page.deleted_at ? 'Restaurar Página' : 'Eliminar Página'}
                            </DangerButton>
                        </div>
                    </div>
                </div>

                {/* Form Actions */}
                <div className="sticky bottom-0 bg-surface border-t border-border shadow-lg p-4 rounded-t-lg flex justify-between">
                    <Link
                        href={route('pages.index')}
                        className="px-6 py-2 border border-border rounded-lg text-primary font-medium hover:bg-gray-50 transition"
                    >
                        Volver
                    </Link>
                    <PrimaryButton disabled={form.processing}>
                        {form.processing ? 'Guardando...' : 'Guardar Cambios'}
                    </PrimaryButton>
                </div>
            </form>

            {/* Media Picker Modal */}
            {showMediaPicker && (
                <MediaPicker
                    onSelect={handleMediaSelect}
                    onClose={() => setShowMediaPicker(false)}
                    type="image"
                />
            )}

            {/* Version History Modal */}
            {showVersionHistory && (
                <VersionHistory
                    pageId={page.id}
                    onClose={() => setShowVersionHistory(false)}
                    canRestore={auth.user?.role?.name === 'Super Admin'}
                />
            )}

            {/* Delete Confirmation Modal */}
            <Modal show={showDeleteModal} onClose={() => setShowDeleteModal(false)}>
                <div className="p-6">
                    <h3 className="text-lg font-medium text-primary mb-4">
                        {page.deleted_at ? 'Restaurar Página' : 'Eliminar Página'}
                    </h3>
                    <p className="text-gray-600 mb-4">
                        {page.deleted_at
                            ? `¿Restaurar la página "${page.title}"?`
                            : `¿Estás seguro de que deseas eliminar la página "${page.title}"? Esta acción se puede deshacer.`}
                    </p>
                    <div className="flex gap-3 justify-end">
                        <SecondaryButton onClick={() => setShowDeleteModal(false)}>
                            Cancelar
                        </SecondaryButton>
                        {page.deleted_at ? (
                            <PrimaryButton onClick={confirmDelete} disabled={form.processing}>
                                {form.processing ? 'Restaurando...' : 'Restaurar'}
                            </PrimaryButton>
                        ) : (
                            <DangerButton onClick={confirmDelete} disabled={form.processing}>
                                {form.processing ? 'Eliminando...' : 'Eliminar'}
                            </DangerButton>
                        )}
                    </div>
                </div>
            </Modal>
        </Authenticated>
    );
}
